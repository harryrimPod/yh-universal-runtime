import { Engine } from '@babylonjs/core/Engines/engine.js';
import { Scene } from '@babylonjs/core/scene.js';
import { Vector3 } from '@babylonjs/core/Maths/math.vector.js';
import { Color3 } from '@babylonjs/core/Maths/math.color.js';
import { HemisphericLight } from '@babylonjs/core/Lights/hemisphericLight.js';
import { DirectionalLight } from '@babylonjs/core/Lights/directionalLight.js';
import { ArcRotateCamera } from '@babylonjs/core/Cameras/arcRotateCamera.js';
import { MeshBuilder } from '@babylonjs/core/Meshes/meshBuilder.js';
import { StandardMaterial } from '@babylonjs/core/Materials/standardMaterial.js';
import { YHEventClient } from '../../src/event-client.mjs';
import { YHBabylonAdapter } from '../../src/adapters/babylonjs.js';
import { releaseOnPageHide } from '../../src/page-lifecycle.mjs';
import '../demo.css';

const $ = selector => document.querySelector(selector);
const canvas = $('#canvas');
const engine = new Engine(canvas, true, { preserveDrawingBuffer: true, stencil: true, powerPreference: 'high-performance' });
const scene = new Scene(engine);
scene.clearColor = new Color3(0.035, 0.045, 0.075).toColor4(1);
const camera = new ArcRotateCamera('camera', -Math.PI / 2, Math.PI / 2.1, 4.2, Vector3.Zero(), scene);
camera.attachControl(canvas, true);
new HemisphericLight('hemisphere', new Vector3(0, 1, 0), scene).intensity = 1.5;
const key = new DirectionalLight('key', new Vector3(-0.5, -1, -1), scene); key.intensity = 1.4;
const orb = MeshBuilder.CreateSphere('YH_Target', { diameter: 1.64, segments: 48 }, scene);
const material = new StandardMaterial('YH_Material', scene);
material.diffuseColor = new Color3(0.58, 0.86, 0.3); material.emissiveColor = new Color3(0.08, 0.14, 0.03); material.specularColor = new Color3(0.7, 0.8, 0.55); orb.material = material;
const wire = MeshBuilder.CreateSphere('YH_Wire', { diameter: 1.67, segments: 26 }, scene);
wire.parent = orb; wire.material = new StandardMaterial('YH_WireMat', scene); wire.material.wireframe = true; wire.material.emissiveColor = new Color3(0.7, 1, 0.45); wire.material.alpha = 0.12;
const yh = new YHEventClient({ url: 'ws://127.0.0.1:8765/ws' });
const adapter = new YHBabylonAdapter(yh, orb);
yh.on('/yh/level', event => $('#level').textContent = Number(event.value).toFixed(2));
yh.on('status', state => { $('#status').textContent = state.status === 'connected' ? '本机桥接已连接' : state.status; $('#dot').classList.toggle('on', state.status === 'connected'); });
yh.connect().then(() => { document.documentElement.dataset.sampleReady = 'babylonjs'; }).catch(error => { $('#status').textContent = error.message; });
$('#sendLevel').addEventListener('click', () => yh.sendControl('/yh/level', Number($('#levelInput').value)));
$('#sendOnset').addEventListener('click', () => yh.sendControl('/yh/onset', 1));
engine.runRenderLoop(() => { const dt = engine.getDeltaTime() / 1000; adapter.update(dt); orb.rotation.y += dt * 0.2; scene.render(); });
window.addEventListener('resize', () => engine.resize());
releaseOnPageHide(() => { adapter.dispose(); yh.close(); engine.dispose(); });
